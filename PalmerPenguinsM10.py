from penguin import Penguin


# ------------------------------------------------------------
# Constants for species names and observation counts
# ------------------------------------------------------------
SP_CHINSTRAP = "Chinstrap"
SP_GENTOO = "Gentoo"
SP_ADELIE = "Adelie"
TOTAL_SPECIES = 3

NUM_CHINSTRAP = 68
NUM_GENTOO = 123
NUM_ADELIE = 151


# ------------------------------------------------------------
# Retrieve a specified penguin observation from the CSV file
# Handle a missing file and raise an exception for a missing row
# ------------------------------------------------------------
def read_penguin_row(row_number):
    penguin_row = ""

    try:
        # Open the dataset and skip its header row.
        with open("PalmerPenguins.csv", "r") as penguin_file:
            penguin_file.readline()

            current_row = 1

            # Search the data rows for the requested observation.
            for row in penguin_file:
                if current_row == row_number:
                    penguin_row = row.strip()
                    break

                current_row += 1

    except FileNotFoundError:
        # Report that the required CSV file could not be opened.
        print("Error: PalmerPenguins.csv was not found.")

    # An empty string indicates that no observation was retrieved.
    # The calling function is responsible for handling this error.
    if penguin_row == "":
        raise ValueError(
            f"Penguin observation {row_number} "
            f"could not be retrieved."
        )

    # Use one return statement at the end of the function.
    return penguin_row


# ------------------------------------------------------------
# Calculate a species' percentage of the total observations
# ------------------------------------------------------------
def calculate_percentage(count, total):
    return count / total * 100


# ------------------------------------------------------------
# Classify a species group according to its percentage
# ------------------------------------------------------------
def classify_species(percent):
    if percent < 25:
        return "small"
    elif percent < 40:
        return "medium"
    else:
        return "large"


# ------------------------------------------------------------
# Determine whether a species is largest, smallest, or middle-sized
# ------------------------------------------------------------
def get_position_description(
        selected_species, largest_species, smallest_species):

    if selected_species == largest_species:
        return "largest"
    elif selected_species == smallest_species:
        return "smallest"
    else:
        return "middle-sized"


# ------------------------------------------------------------
# Display species statistics using the three parallel lists
# ------------------------------------------------------------
def display_species_statistics(names, counts, percentages):
    for index, species in enumerate(names):
        print(f"{species}: {counts[index]} ({percentages[index]:.2f}%)")


# ------------------------------------------------------------
# Display the formatted information for one penguin observation
# ------------------------------------------------------------
def display_penguin_observation(
        sample_number,
        species,
        bill_length,
        bill_depth,
        body_mass,
        sex):

    print("\nSample Penguin Observation")
    print(f"{'Sample Number:':<18}{sample_number}")
    print(f"{'Species:':<18}{species}")
    print(f"{'Bill length:':<18}{bill_length:.1f} mm")
    print(f"{'Bill depth:':<18}{bill_depth:.1f} mm")
    print(f"{'Body mass:':<18}{body_mass} g")
    print(f"{'Sex:':<18}{sex}")


# ------------------------------------------------------------
# Retrieve, convert, and display one CSV observation
# Handle retrieval errors, invalid numeric data, and missing fields
# ------------------------------------------------------------
def process_penguin_row(row_number):
    try:
        # Retrieve the requested observation.
        penguin_row = read_penguin_row(row_number)

        # Display the original CSV row.
        print(f"\nSample dataset row: {penguin_row}")

        # Split the CSV row into individual fields.
        penguin_data = penguin_row.split(",")
        print(penguin_data)

        # Convert numeric fields and retrieve text fields.
        sample_number = int(penguin_data[0])
        species = penguin_data[1]
        bill_length = float(penguin_data[2])
        bill_depth = float(penguin_data[3])
        body_mass = int(penguin_data[5])
        sex = penguin_data[6]

        # Display the observation using the existing function.
        display_penguin_observation(
            sample_number,
            species,
            bill_length,
            bill_depth,
            body_mass,
            sex
        )

    except ValueError as excpt:
        # Handle a missing observation or an invalid numeric value.
        print(f"Error: {excpt}")

    except IndexError:
        # Handle an observation that does not contain enough fields.
        print("Error: The penguin observation is incomplete.")


# ------------------------------------------------------------
# Main program: analyze observations and explore the dataset
# ------------------------------------------------------------
def main():
    # --------------------------------------------------------
    # Create parallel lists for species names and counts
    # --------------------------------------------------------
    species_names = [
        SP_CHINSTRAP,
        SP_GENTOO,
        SP_ADELIE
    ]

    species_counts = [
        NUM_CHINSTRAP,
        NUM_GENTOO,
        NUM_ADELIE
    ]

    # --------------------------------------------------------
    # Calculate the total and average observation counts
    # --------------------------------------------------------
    total_species = len(species_names)
    total_penguins = sum(species_counts)
    average_penguins = total_penguins / total_species
    rounded_average = round(average_penguins)

    # --------------------------------------------------------
    # Calculate each species' percentage of the dataset
    # --------------------------------------------------------
    chinstrap_percent = calculate_percentage(
        species_counts[0], total_penguins
    )
    gentoo_percent = calculate_percentage(
        species_counts[1], total_penguins
    )
    adelie_percent = calculate_percentage(
        species_counts[2], total_penguins
    )

    # Store percentages in a third parallel list.
    species_percentages = [
        chinstrap_percent,
        gentoo_percent,
        adelie_percent
    ]

    # --------------------------------------------------------
    # Identify the largest and smallest species by count
    # --------------------------------------------------------
    largest_count = max(species_counts)
    smallest_count = min(species_counts)

    largest_index = species_counts.index(largest_count)
    smallest_index = species_counts.index(smallest_count)

    largest_species = species_names[largest_index]
    smallest_species = species_names[smallest_index]

    # --------------------------------------------------------
    # Introduce the three penguin species
    # --------------------------------------------------------
    print("Introducing the Palmer Penguins:\n")
    print("    " + SP_CHINSTRAP + "!")
    print("    " + SP_GENTOO + "!")
    print("and last but not least...\n")
    print("    " + SP_ADELIE + "!\n")

    # --------------------------------------------------------
    # Display dataset totals and species statistics
    # --------------------------------------------------------
    print(f"There are a total of {TOTAL_SPECIES} species in this dataset.")
    print(f"There are a total of {total_penguins} penguins in the dataset.")
    print(
        f"The average number of penguins per species is "
        f"{average_penguins:.1f}."
    )
    print(f"The average rounded up is {rounded_average} penguins.")

    display_species_statistics(
        species_names,
        species_counts,
        species_percentages
    )

    print(
        f"The species with the most observations is {largest_species} "
        f"with {largest_count} penguins."
    )
    print(
        f"The species with the fewest observations is {smallest_species} "
        f"with {smallest_count} penguins."
    )
    print()

    # --------------------------------------------------------
    # Process and display two sample observations
    # --------------------------------------------------------
    process_penguin_row(1)
    process_penguin_row(150)

    # --------------------------------------------------------
    # Demonstrate handling an observation that does not exist
    # The handled exception allows the program to continue
    # --------------------------------------------------------
    print("\nException Handling Demonstration")
    process_penguin_row(999)

    # --------------------------------------------------------
    # Collect body masses from five sample observations
    # --------------------------------------------------------
    sample_rows = [1, 2, 3, 4, 5]
    body_masses = []

    for row_number in sample_rows:
        # Retrieve and split the current observation.
        penguin_row = read_penguin_row(row_number)
        penguin_data = penguin_row.split(",")

        # Convert the body mass and add it to the list.
        body_mass = int(penguin_data[5])
        body_masses.append(body_mass)

    print("\nSample Body Masses")
    print(body_masses)

    # --------------------------------------------------------
    # Calculate and display body mass summary statistics
    # --------------------------------------------------------
    observation_count = len(body_masses)
    total_body_mass = sum(body_masses)
    smallest_body_mass = min(body_masses)
    largest_body_mass = max(body_masses)
    average_body_mass = total_body_mass / observation_count

    print("\nBody Mass Summary")
    print(f"Observations: {observation_count}")
    print(f"Total body mass: {total_body_mass} g")
    print(f"Smallest body mass: {smallest_body_mass} g")
    print(f"Largest body mass: {largest_body_mass} g")
    print(f"Average body mass: {average_body_mass:.2f} g")

    # --------------------------------------------------------
    # Create a dictionary associating species with their counts
    # --------------------------------------------------------
    species_dictionary = {
        SP_CHINSTRAP: NUM_CHINSTRAP,
        SP_GENTOO: NUM_GENTOO,
        SP_ADELIE: NUM_ADELIE
    }

    print("\nSpecies Counts Using a Dictionary")

    # Retrieve and display each count using its species key.
    for species in species_dictionary:
        count = species_dictionary[species]
        print(f"{species}: {count}")

    print()

    # --------------------------------------------------------
    # Create one Penguin object from the first observation
    # --------------------------------------------------------
    penguin_row = read_penguin_row(1)
    penguin_data = penguin_row.split(",")

    sample_number = int(penguin_data[0])
    species = penguin_data[1]
    body_mass = int(penguin_data[5])

    sample_penguin = Penguin(sample_number, species, body_mass)

    # Display the object's information using its method.
    print("\nPenguin Object Demonstration")
    sample_penguin.display_info()

    # --------------------------------------------------------
    # Create a list containing five Penguin objects
    # --------------------------------------------------------
    sample_rows = [1, 2, 3, 4, 5]
    penguin_objects = []

    for row_number in sample_rows:
        # Retrieve the data needed to create each object.
        penguin_row = read_penguin_row(row_number)
        penguin_data = penguin_row.split(",")

        sample_number = int(penguin_data[0])
        species = penguin_data[1]
        body_mass = int(penguin_data[5])

        # Create the object and append it to the list.
        sample_penguin = Penguin(sample_number, species, body_mass)
        penguin_objects.append(sample_penguin)

    # --------------------------------------------------------
    # Display each Penguin object in the list
    # --------------------------------------------------------
    print("\nPenguin Objects")

    for penguin in penguin_objects:
        penguin.display_info()

    # --------------------------------------------------------
    # Calculate body mass statistics using object attributes
    # --------------------------------------------------------
    total_object_mass = 0

    for penguin in penguin_objects:
        total_object_mass += penguin.body_mass

    average_object_mass = total_object_mass / len(penguin_objects)

    print("\nObject-Based Body Mass Summary")
    print(f"Observations: {len(penguin_objects)}")
    print(f"Total body mass: {total_object_mass} g")
    print(f"Average body mass: {average_object_mass:.2f} g")

    # --------------------------------------------------------
    # Initialize interactive exploration
    # Count valid species selections, not sample requests
    # --------------------------------------------------------
    valid_selections = 0

    print("\nExplore the Palmer Penguins")
    print("Enter Chinstrap, Gentoo, Adelie, Sample, or Done.")

    species_choice = input("Enter a species: ")

    # --------------------------------------------------------
    # Continue exploring until the user enters Done
    # --------------------------------------------------------
    while species_choice != "Done":
        if species_choice == "Sample":
            # ------------------------------------------------
            # Process a sample request and handle invalid input
            # ------------------------------------------------
            try:
                sample_number = int(input("Enter a sample number: "))
                process_penguin_row(sample_number)

            except ValueError:
                # Handle input that cannot be converted to an integer.
                print("Error: Please enter a valid integer sample number.")

            finally:
                # Confirm completion after every sample request.
                print("Sample request completed.")

        elif species_choice not in species_names:
            # Reject entries that are not recognized commands.
            print("That is not a valid species.")

        else:
            # ------------------------------------------------
            # Process a valid species selection
            # ------------------------------------------------
            valid_selections = valid_selections + 1

            # Determine the selected species' parallel-list index.
            if species_choice == species_names[0]:
                selected_index = 0
            elif species_choice == species_names[1]:
                selected_index = 1
            else:
                selected_index = 2

            # Retrieve the selected species' statistics.
            selected_species = species_names[selected_index]
            selected_count = species_counts[selected_index]
            selected_percent = species_percentages[selected_index]

            # Classify the species based on its dataset percentage.
            size_category = classify_species(selected_percent)

            # Determine its position relative to the other species.
            position_description = get_position_description(
                selected_species,
                largest_species,
                smallest_species
            )

            # Compare its observation count with the dataset average.
            average_position = (
                "above" if selected_count > average_penguins else "below"
            )

            # ------------------------------------------------
            # Display the selected species' statistics
            # ------------------------------------------------
            print(f"Species: {selected_species}")
            print(f"Count: {selected_count}")
            print(f"Percentage: {selected_percent:.2f}%")
            print(
                f"This species represents a {size_category} "
                f"portion of the dataset."
            )
            print(
                f"It is the {position_description} species "
                f"in the dataset."
            )
            print(f"Its count is {average_position} the average.")

        # Prompt again after a species selection or sample request.
        print()
        species_choice = input("Enter another species: ")

    # --------------------------------------------------------
    # Display the final species exploration summary
    # --------------------------------------------------------
    print(f"You explored {valid_selections} valid penguin species.")
    print("Exploration complete.")


